# 3. Peça o raio de um círculo e calcule a área. Use 3.14159 como valor de pi.

print("--- BEM VINDO A ESCOLINHA DE MATEMÁTICA DO PROFESSORZINHO EWERTON ---")
print("A FÓRMULA DO RAIO DO CÍRCULO É: A = 3.14159 (pi) * r*r .   ")

raio = float(input("DIGITE O RAIO DO SEU CÍRCULO EM CENTÍMETROS QUERIDO ALUNO: "))
area = 3.14159 * raio * raio

print(f"A ÁREA DO SEU CÍRCULO, MEU CARO ALUNO, É DE APROXIMADAMENTE {area:.2f} CENTÍMETROS.")